// ============================================================
// 1. 타입 정의
// ============================================================

/** 지원하는 마케팅 채널 */
export type Channel =
  | '메타 광고'
  | '인스타그램'
  | '상세페이지'
  | 'CRM'

/** 카피라이팅 프레임워크 */
export type Framework =
  | 'AIDA'
  | 'PAS'
  | 'FAB'

/** 프롬프트 생성에 필요한 입력 데이터 */
export type FormData = {
  // 브랜드 정보
  brand: string
  description: string
  tone: string
  keywords: string
  forbidden: string

  // 캠페인 정보
  channel: Channel
  goal: string
  audience: string
  product: string
  benefit: string

  // 카피라이팅 프레임워크
  framework: Framework
}

// ============================================================
// 2. 초기 입력값
// ============================================================

export const initialForm: FormData = {
  // 브랜드 정보
  brand: '',
  description: '',
  tone: '친근하고 명료한',
  keywords: '',
  forbidden: '',

  // 캠페인 정보
  channel: '메타 광고',
  goal: '전환 유도',
  audience: '',
  product: '',
  benefit: '',

  // 프레임워크
  framework: 'AIDA',
}

// ============================================================
// 3. 채널별 카피라이팅 규칙
// ============================================================

const channelRules: Record<Channel, string> = {
  '메타 광고': [
    '피드 광고에 적합한 짧은 첫 문장(훅),',
    '설득력 있는 본문, 명확한 CTA를 작성한다.',
    '과장·오해를 유발하는 표현과',
    '개인의 민감한 특성을 단정하는 표현을 피한다.',
  ].join(' '),

  '인스타그램': [
    '스크롤을 멈추게 하는 첫 문장,',
    '모바일에서 읽기 쉬운 짧은 문단,',
    '자연스러운 참여 유도 문장과',
    '관련 해시태그를 작성한다.',
  ].join(' '),

  '상세페이지': [
    '고객의 문제와 제품의 해결 가치,',
    '핵심 혜택, 구매 전 확인 사항, CTA를',
    '정보 위계에 따라 섹션별로 구성한다.',
  ].join(' '),

  'CRM': [
    '기존 고객과의 관계를 고려해',
    '메시지를 간결하게 작성한다.',
    '제목/첫 문장/본문/CTA를 분리하고',
    '과도한 긴급성·스팸성 문구를 피한다.',
  ].join(' '),
}

// ============================================================
// 4. 카피라이팅 프레임워크 규칙
// ============================================================

const frameworkRules: Record<Framework, string> = {
  AIDA:
    'Attention(주목) → Interest(관심) → ' +
    'Desire(욕구) → Action(행동)의 흐름으로 작성한다.',

  PAS:
    'Problem(문제) → Agitate(문제의 영향) → ' +
    'Solution(해결)의 흐름으로 작성한다.',

  FAB:
    'Feature(특징) → Advantage(장점) → ' +
    'Benefit(고객 혜택)의 흐름으로 작성한다.',
}

// ============================================================
// 5. 유틸리티 함수
// ============================================================

/**
 * 입력값 정리
 *
 * - 앞뒤 공백 제거
 * - 빈 값이면 정보 미입력 안내 문구 반환
 * - 입력하지 않은 정보를 AI가 추측하지 않도록 유도
 */
const clean = (value: string): string => {
  const trimmed = value.trim()

  return (
    trimmed ||
    '정보 미입력 (추측하지 말고 필요한 경우 확인 질문)'
  )
}

// ============================================================
// 6. 프롬프트 생성 함수
// ============================================================

/**
 * 사용자가 입력한 브랜드·캠페인 정보를 바탕으로
 * 한국어 마케팅 카피라이팅 프롬프트 생성
 *
 * @param f - 사용자 입력 데이터
 * @returns 완성된 한국어 프롬프트
 */
export function generatePrompt(f: FormData): string {
  return `
# 역할

당신은 브랜드 가이드를 준수하는 한국어 마케팅 카피라이터입니다.
아래 제공된 사실만 근거로 ${f.channel}용 카피를 작성하세요.

# 브랜드 정보

- 브랜드명: ${clean(f.brand)}
- 브랜드 소개: ${clean(f.description)}
- 톤앤매너: ${f.tone}
- 핵심 키워드: ${clean(f.keywords)}
- 금지 표현: ${clean(f.forbidden)}

# 캠페인 정보

- 채널: ${f.channel}
- 목표: ${clean(f.goal)}
- 타깃: ${clean(f.audience)}
- 상품/서비스: ${clean(f.product)}
- 핵심 혜택: ${clean(f.benefit)}

# 채널별 작성 규칙

${channelRules[f.channel]}

# 카피라이팅 프레임워크: ${f.framework}

${frameworkRules[f.framework]}

# 반드시 지킬 조건

1. 브랜드 톤앤매너를 일관되게 유지하고 금지 표현은 어떤 형태로도 사용하지 마세요.
2. 제공되지 않은 가격, 할인율, 성과 수치, 인증, 수상 이력, 후기, 고객 사례, 효능, 보장 내용은 만들어내지 마세요.
3. 사실 확인이 필요한 주장은 임의로 단정하지 말고 [확인 필요]로 표시하세요.
4. 타깃을 존중하고 오해의 소지가 있는 과장·공포·차별 표현을 피하세요.
5. 입력값에 없는 필수 정보는 추측하지 말고 마지막에 질문으로 정리하세요.

# 출력 형식

- 서로 다른 방향의 카피 3안을 한국어로 제시하세요.
- 각 안마다 다음 항목을 구분하세요.
  - 컨셉
  - 헤드라인
  - 본문
  - CTA
  - 적용한 ${f.framework} 구조
- 각 안의 차별점과 채널 적합성을 한 문장으로 설명하세요.
- 마지막에 '검증 필요 사항'을 정리하세요.
- 불필요한 서론 없이 결과부터 작성하세요.
`.trim()
}
