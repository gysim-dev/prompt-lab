// ============================================================
// 5. 유틸리티 함수
// ============================================================

/**
 * 입력값 정리
 *
 * - 앞뒤 공백 제거
 * - 빈 값이면 정보 미입력 안내 문구 반환
 * - 입력하지 않은 정보를 AI가 추측하지 않도록 유도
 */
const clean = (value: string): string => {
  const trimmed = value.trim()

  return (
    trimmed ||
    '정보 미입력 (추측하지 말고 필요한 경우 확인 질문)'
  )
}

// ============================================================
// 6. 프롬프트 생성 함수
// ============================================================

/**
 * 사용자가 입력한 브랜드·캠페인 정보를 바탕으로
 * 한국어 마케팅 카피라이팅 프롬프트 생성
 *
 * @param f - 사용자 입력 데이터
 * @returns 완성된 한국어 프롬프트
 */
export function generatePrompt(f: FormData): string {
  return `
# 역할

당신은 브랜드 가이드를 준수하는 한국어 마케팅 카피라이터입니다.
아래 제공된 사실만 근거로 ${f.channel}용 카피를 작성하세요.

# 브랜드 정보

- 브랜드명: ${clean(f.brand)}
- 브랜드 소개: ${clean(f.description)}
- 톤앤매너: ${f.tone}
- 핵심 키워드: ${clean(f.keywords)}
- 금지 표현: ${clean(f.forbidden)}

# 캠페인 정보

- 채널: ${f.channel}
- 목표: ${clean(f.goal)}
- 타깃: ${clean(f.audience)}
- 상품/서비스: ${clean(f.product)}
- 핵심 혜택: ${clean(f.benefit)}

# 채널별 작성 규칙

${channelRules[f.channel]}

# 카피라이팅 프레임워크: ${f.framework}

${frameworkRules[f.framework]}

# 반드시 지킬 조건

1. 브랜드 톤앤매너를 일관되게 유지하고 금지 표현은 어떤 형태로도 사용하지 마세요.
2. 제공되지 않은 가격, 할인율, 성과 수치, 인증, 수상 이력, 후기, 고객 사례, 효능, 보장 내용은 만들어내지 마세요.
3. 사실 확인이 필요한 주장은 임의로 단정하지 말고 [확인 필요]로 표시하세요.
4. 타깃을 존중하고 오해의 소지가 있는 과장·공포·차별 표현을 피하세요.
5. 입력값에 없는 필수 정보는 추측하지 말고 마지막에 질문으로 정리하세요.

# 출력 형식

- 서로 다른 방향의 카피 3안을 한국어로 제시하세요.
- 각 안마다 다음 항목을 구분하세요.

${channelOutputRules[f.channel]}

- 각 안의 차별점과 채널 적합성을 한 문장으로 설명하세요.
- 마지막에 '검증 필요 사항'을 정리하세요.
- 불필요한 서론 없이 결과부터 작성하세요.

`.trim()
}
